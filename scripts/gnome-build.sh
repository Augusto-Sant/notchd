#!/usr/bin/env bash
# Assembles the GNOME Shell extension into one self-contained folder:
# hosts/gnome/ as is, plus lib/, the UI-side plain-JS files of core/ turned
# into ES modules (every top-level `function` and `var` exported). The
# sources stay ES5 for QML and Node; the copies exist only in the output.
#
#   scripts/gnome-build.sh <out-dir>
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
out=$1
uuid=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["uuid"])' "$root/hosts/gnome/metadata.json")
dest="$out/$uuid"

rm -rf -- "$dest"
mkdir -p -- "$dest/lib"
cp -r -- "$root/hosts/gnome/." "$dest/"

shared=(core/client/Protocol.js core/client/prims/Tree.js core/Outline.js core/Position.js)
for src in "${shared[@]}"; do
  name=$(basename "$src")
  names=$(grep -oE '^(function|var) [A-Za-z_$][A-Za-z0-9_$]*' "$root/$src" | awk '{print $2}' | sort -u | paste -sd, -)
  {
    echo "// Generated by scripts/gnome-build.sh from $src: do not edit."
    cat "$root/$src"
    echo
    echo "export { ${names//,/, } }"
  } > "$dest/lib/$name"
done

# The extension's GSettings schema (its keybinding), compiled where GNOME
# looks for it: schemas/ in the extension's folder.
glib-compile-schemas -- "$dest/schemas"

echo "$dest"
